def tr(language: str, key: str, **values) -> str:
    catalog = TEXT.get(language, TEXT["en"])
    return catalog.get(key, TEXT["en"].get(key, key)).format(**values)


def mode_text(language: str, mode: str, include_hint: bool = False) -> str:
    """Render a consistent mode label and optional parenthesized switch hint."""
    safe_mode = mode if mode in {"single", "multi"} else "multi"
    mode_name = tr(language, "mode_single" if safe_mode == "single" else "mode_multi")
    if not include_hint:
        return mode_name
    next_mode = "multi" if safe_mode == "single" else "single"
    command = f"/autoquests mode {next_mode}"
    return f"{mode_name} ({tr(language, 'mode_change_hint', command=command)})"
